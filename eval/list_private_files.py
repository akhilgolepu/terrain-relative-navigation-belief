#!/usr/bin/env python3
"""List tracked files that contain label-derived positions (UAV-VisLoc: no redistribution).

A tracked CSV is flagged if its header has a position column; a tracked JSON if its keys name one
(position or coordinate columns (true_e/true_n, prior_e/prior_n, fix_e/fix_n, est_e/est_n, cand_east/cand_north,
east/north of candidates, lat/lon, latitude/longitude). Writes docs/private_files.md.
Usage: python3 eval/list_private_files.py
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
POS_COLS = {"true_e", "true_n", "prior_e", "prior_n", "fix_e", "fix_n", "est_e", "est_n", "cand_east", "cand_north",
            "east", "north", "lat", "lon", "latitude", "longitude"}
PATTERN = re.compile(r'\b(true_e|true_n|prior_e|prior_n|fix_e|fix_n|est_e|est_n|cand_east|cand_north|"east"|"north"|'
                     r'lat|lon|latitude|longitude)\b')


def main() -> int:
    files = subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True, text=True).stdout.split()
    flagged = {}
    for f in files:
        if f.endswith(".csv"):
            header = (ROOT / f).read_text(errors="ignore").splitlines()[:1]
            cols = {c.strip() for c in header[0].split(",")} if header else set()
            m = sorted(cols & POS_COLS)
        elif f.endswith(".json"):
            m = sorted(set(PATTERN.findall((ROOT / f).read_text(errors="ignore")[:200000])))
        else:
            continue
        if m:
            flagged[f] = m
    by_dir: dict[str, list] = {}
    for f, cols in flagged.items():
        by_dir.setdefault(str(Path(f).parent), []).append((Path(f).name, cols))
    lines = ["# Files that must stay private (label-derived positions)", "",
             "UAV-VisLoc is academic use only and forbids redistribution. The files below are tracked in git and contain "
             "positions derived from the dataset labels (ENU east/north of labels, priors, fixes or candidates, or "
             "latitude/longitude). The repository stays private; nothing is pushed. Before anything is published, these "
             "files (and their git history) must be removed, or the publication must be a fresh repository without them.",
             "", "Not tracked at all (git-ignored, stay on this machine): dataset images, map chips, overlays, failure "
             "overlays, matcher caches (`eval/results/week7/closed_loop/runs/*.cache.jsonl`, "
             "`eval/results/test_flight11/private/`), the rosbag (`~/data/rosbags/`).", "",
             f"Generated by `python3 eval/list_private_files.py`: {len(flagged)} files.", "",
             "| Folder | Files | Position columns found |", "|---|---|---|"]
    for d, items in sorted(by_dir.items()):
        cols = sorted({c for _, cs in items for c in cs})
        names = ", ".join(n for n, _ in sorted(items)) if len(items) <= 6 else f"{len(items)} files ({items[0][0]} ...)"
        lines.append(f"| `{d}` | {names} | {', '.join(cols)} |")
    lines += ["", "Safe to publish (no positions): code, `docs/` text and figures, summary tables (`*.md`) and the error-only "
              "CSVs not listed above (they hold errors in metres, not positions)."]
    (ROOT / "docs/private_files.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[-len(by_dir) - 3:]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
